const { contextBridge, ipcRenderer } = require('electron');
const inv = (c, ...a) => ipcRenderer.invoke(c, ...a);
contextBridge.exposeInMainWorld('api', {
  getStore: () => inv('store:get'),
  getI18n: () => inv('i18n:get'),
  setSettings: (p) => inv('settings:set', p),
  saveLast: (d) => inv('last:save', d),
  connect: (id) => inv('rpc:connect', id),
  disconnect: () => inv('rpc:disconnect'),
  apply: (f) => inv('rpc:apply', f),
  clear: () => inv('rpc:clear'),
  savePreset: (n, d) => inv('preset:save', n, d),
  deletePreset: (n) => inv('preset:delete', n),
  exportPreset: (n) => inv('preset:export', n),
  importPreset: () => inv('preset:import'),
  pickAsset: () => inv('asset:pickLocal'),
  addAsset: (n, u) => inv('asset:add', n, u),
  removeAsset: (n) => inv('asset:remove', n),
  setBotToken: (t) => inv('token:set', t),
  setAppIcon: () => inv('appicon:set'),
  getStats: () => inv('sys:stats'),
  onRotation: (cb) => ipcRenderer.on('rotation', (_, d) => cb(d)),
  onSettings: (cb) => ipcRenderer.on('settings', (_, d) => cb(d)),
  onPresetApplied: (cb) => ipcRenderer.on('preset-applied', (_, d) => cb(d)),
  openExternal: (u) => inv('open:external', u),
  getUpdate: () => inv('update:state'),
  checkUpdate: () => inv('update:check'),
  downloadUpdate: () => inv('update:download'),
  installUpdate: () => inv('update:install'),
  openReleases: () => inv('update:manual'),
  onUpdate: (cb) => ipcRenderer.on('update', (_, d) => cb(d)),
  onStatus: (cb) => ipcRenderer.on('status', (_, d) => cb(d)),
});
